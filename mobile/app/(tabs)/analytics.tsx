import React, { useState } from 'react';
import {
  View,
  Text,
  StyleSheet,
  ScrollView,
  TouchableOpacity,
  Share,
  Alert,
} from 'react-native';
import { PieChart, TrendingDown, Share2, Award, Calendar, ArrowUpRight, ArrowDownRight } from 'lucide-react-native';
import { ScreenWrapper } from '../../src/components/ScreenWrapper';
import { Header } from '../../src/components/Header';
import { CategoryBreakdown } from '../../src/components/CategoryBreakdown';
import { MonthSelectorModal } from '../../src/components/MonthSelectorModal';
import { useBudget } from '../../src/context/BudgetContext';
import { useTheme } from '../../src/context/ThemeContext';
import { MONTH_NAMES } from '../../src/constants/theme';
import { formatCurrency } from '../../src/components/SummaryCards';

export default function AnalyticsScreen() {
  const { colors } = useTheme();
  const {
    selectedMonth,
    selectedYear,
    summary,
    expenses,
    income,
  } = useBudget();

  const [monthModalVisible, setMonthModalVisible] = useState(false);

  const monthName = MONTH_NAMES[selectedMonth - 1];
  const totalInc = parseFloat(summary.totalIncome) || 0;
  const totalExp = parseFloat(summary.totalExpenses) || 0;
  const remBal = parseFloat(summary.remainingBalance) || 0;
  const savingsRate = totalInc > 0 ? Math.max(((remBal / totalInc) * 100), 0).toFixed(1) : '0.0';

  // Export report to share (bonus feature)
  const handleExportSummary = async () => {
    try {
      let report = `📊 MONTHLY BUDGET REPORT - ${monthName.toUpperCase()} ${selectedYear}\n`;
      report += `----------------------------------------\n`;
      report += `Total Income:    ${formatCurrency(totalInc)}\n`;
      report += `Total Expenses:  ${formatCurrency(totalExp)}\n`;
      report += `Remaining Bal:   ${formatCurrency(remBal)}\n`;
      report += `Savings Rate:    ${savingsRate}%\n`;
      report += `Transactions:    ${summary.expenseCount}\n\n`;
      report += `CATEGORY BREAKDOWN:\n`;
      for (const [cat, amt] of Object.entries(summary.categoryBreakdown || {})) {
        report += ` - ${cat}: ${formatCurrency(amt)}\n`;
      }
      report += `\nEXPENSE TRANSACTIONS:\n`;
      expenses.forEach((e, idx) => {
        report += `${idx + 1}. ${e.name} (${e.category}) - ${formatCurrency(e.amount)} [${new Date(e.date).toLocaleDateString()}]\n`;
      });
      report += `----------------------------------------\nGenerated by Monthly Budget Tracker Mobile App`;

      await Share.share({
        message: report,
        title: `Budget Report ${monthName} ${selectedYear}`,
      });
    } catch (err: any) {
      Alert.alert('Export Error', err.message || 'Unable to share report');
    }
  };

  return (
    <ScreenWrapper>
      <Header
        title="Financial Analytics"
        subtitle={`Insights for ${monthName} ${selectedYear}`}
        onOpenMonthPicker={() => setMonthModalVisible(true)}
      />

      <ScrollView contentContainerStyle={styles.scrollContent} showsVerticalScrollIndicator={false}>
        {/* KPI Grid */}
        <View style={styles.kpiGrid}>
          {/* Savings Rate Card */}
          <View
            style={[
              styles.kpiCard,
              { backgroundColor: colors.surface, borderColor: colors.border },
            ]}
          >
            <View style={styles.kpiHeader}>
              <Award size={16} color={colors.primary} />
              <Text style={[styles.kpiLabel, { color: colors.textMuted }]}>Savings Rate</Text>
            </View>
            <Text style={[styles.kpiValue, { color: colors.income }]}>{savingsRate}%</Text>
            <Text style={[styles.kpiSub, { color: colors.textDim }]}>of income retained</Text>
          </View>

          {/* Average per Transaction */}
          <View
            style={[
              styles.kpiCard,
              { backgroundColor: colors.surface, borderColor: colors.border },
            ]}
          >
            <View style={styles.kpiHeader}>
              <TrendingDown size={16} color={colors.expense} />
              <Text style={[styles.kpiLabel, { color: colors.textMuted }]}>Avg / Expense</Text>
            </View>
            <Text style={[styles.kpiValue, { color: colors.text }]}>
              {summary.expenseCount > 0
                ? formatCurrency(totalExp / summary.expenseCount)
                : 'Rs. 0'}
            </Text>
            <Text style={[styles.kpiSub, { color: colors.textDim }]}>
              across {summary.expenseCount} entries
            </Text>
          </View>
        </View>

        {/* Category Breakdown Component */}
        <CategoryBreakdown />

        {/* Budget Health Summary */}
        <View
          style={[
            styles.healthCard,
            { backgroundColor: colors.surface, borderColor: colors.border },
          ]}
        >
          <Text style={[styles.cardTitle, { color: colors.text }]}>Budget Utilization</Text>

          <View style={styles.meterRow}>
            <Text style={[styles.meterLabel, { color: colors.textMuted }]}>
              Spent ({summary.percentageSpent.toFixed(1)}%)
            </Text>
            <Text style={[styles.meterAmount, { color: colors.text }]}>
              {formatCurrency(totalExp)} / {formatCurrency(totalInc)}
            </Text>
          </View>

          <View style={[styles.meterTrack, { backgroundColor: colors.surfaceVariant }]}>
            <View
              style={[
                styles.meterFill,
                {
                  width: `${Math.min(summary.percentageSpent, 100)}%`,
                  backgroundColor: summary.isOverspent
                    ? colors.expense
                    : summary.isNearLimit
                    ? colors.warning
                    : colors.income,
                },
              ]}
            />
          </View>

          <Text style={[styles.meterAdvice, { color: colors.textMuted }]}>
            {summary.isOverspent
              ? '⚠️ You have exceeded your budget. Consider reducing non-essential expenses.'
              : summary.isNearLimit
              ? '⚡ You are near your 80% spending threshold. Spend cautiously for the rest of the month.'
              : '✅ Your spending pace is healthy and well within your monthly allocation.'}
          </Text>
        </View>

        {/* Export / Share Report (Bonus) */}
        <TouchableOpacity
          style={[styles.exportBtn, { backgroundColor: colors.surfaceVariant, borderColor: colors.border }]}
          onPress={handleExportSummary}
          activeOpacity={0.8}
        >
          <Share2 size={18} color={colors.primary} />
          <Text style={[styles.exportBtnText, { color: colors.primary }]}>
            Export / Share {monthName} Budget Report
          </Text>
        </TouchableOpacity>
      </ScrollView>

      <MonthSelectorModal
        visible={monthModalVisible}
        onClose={() => setMonthModalVisible(false)}
      />
    </ScreenWrapper>
  );
}

